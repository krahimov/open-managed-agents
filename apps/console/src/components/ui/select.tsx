        "relative flex min-h-8 cursor-pointer items-center gap-2 rounded-md px-2 py-1.5 text-small-size outline-hidden select-none transition-colors duration-75 w-full pr-8 text-fg focus:bg-bg-hover data-disabled:pointer-events-none data-disabled:opacity-45 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2",
